#!/usr/bin/env bash
# Purpose: make the shared tutor-system node_modules tree resolvable inside a
# fresh checkout (including fast-multi-agent-tdd replay worktrees), which do not
# contain gitignored dependencies. Run from anywhere; idempotent.
set -euo pipefail

repo_root="$(git rev-parse --show-toplevel)"
link="$repo_root/tutor-system/node_modules"
target="${TDD_NODE_MODULES_SOURCE:-/Users/admin/Documents/GitHub.nosynchr/PhishingTrainingProgram/tutor-system/node_modules}"

if [ -e "$link" ] || [ -L "$link" ]; then
  echo "node_modules already present at $link"
  exit 0
fi

if [ ! -d "$target" ]; then
  echo "dependency source is missing: $target" >&2
  exit 1
fi

ln -s "$target" "$link"
echo "linked $link -> $target"
